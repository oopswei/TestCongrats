-- 桃竹區部賀報製作：私有新屋人員職稱名單
-- 在 Supabase SQL Editor 執行一次。
create table if not exists public.new_house_staff (
  id bigint generated by default as identity primary key,
  name text not null,
  job text not null,
  created_at timestamptz not null default now(),
  constraint new_house_staff_name_job_unique unique (name, job)
);

alter table public.new_house_staff enable row level security;

-- 前端登入後只能讀取名單，不能透過網頁新增、修改或刪除。
revoke all on table public.new_house_staff from anon;
revoke all on table public.new_house_staff from authenticated;
grant select on table public.new_house_staff to authenticated;

drop policy if exists "Authenticated users can read staff list" on public.new_house_staff;
create policy "Authenticated users can read staff list"
on public.new_house_staff
for select
to authenticated
using (true);
